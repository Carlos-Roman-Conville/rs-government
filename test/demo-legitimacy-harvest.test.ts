import { createHash } from 'node:crypto'
import { fileURLToPath } from 'node:url'
import { beforeAll, describe, expect, it } from 'vitest'
import { streams } from '@rex/kernel'
import { loadManorFixture } from '../src/demo/fixture.ts'
import { createHarvestStubs, runLegitimacyHarvest } from '../src/demo/legitimacy-harvest.ts'
import type { HarvestCommand, HarvestRunOptions, HarvestStubParameters, StubOwnerSnapshot } from '../src/demo/legitimacy-harvest.ts'
import { loadProcedures } from '../src/law/procedure.ts'

const root = fileURLToPath(new URL('../', import.meta.url))
const fixtures = { A: loadManorFixture(root, 'A'), B: loadManorFixture(root, 'B') }
const procedures = loadProcedures(root).procedures
const first = fixtures.A.households[0].id
// Every value here is a host modelling choice, not a historical claim or default.
const parameters: HarvestStubParameters = {
  note: 'Test modelling choices: five 365-day years, harvest/deadline on day 0; five acres, no initial stores, 90% harvest loss; pay available grain; beliefs read post-levy food adequacy.',
  institution: 'authority.manor-court', domain: 'levy', backingActor: 'office.beadle',
  agents: [first], granaryGrain: 0, shockMultiplier: 0.1,
  households: Object.fromEntries(fixtures.A.households.map(h => [h.id, { acres: 5, grain: 0, belief: 1, weight: 1, capacity: 1 }])),
  // Illustrative expected-cost choice: pay as much as possible. No belief input.
  choosePayment: (row, available) => Math.min(row.owed!, available),
  // Explicit stand-in supplied by this test host, with no Government update rule.
  updateBelief: experience => ({ belief: Math.min(1, experience.grain / experience.annualNeed),
    cause: `Cognition stub: post-levy grain ${experience.grain} / annual subsistence ${experience.annualNeed}; paid ${experience.paid} attributed to court` }),
  // An observed act/outcome supplied by a host, never generated by Government.
  acts: day => day.shock ? [{ actor: first, action: 'steal', object: 'inventory.lord-granary',
    place: fixtures.A.place, day: day.day, attempted: true, succeeded: true }] : [],
  present: (_breach, procedure) => ({ witnesses: procedure ? [first] : [], present: procedure !== null }),
}

function freeze<T>(value: T): T {
  if (value && typeof value === 'object') {
    Object.values(value).forEach(freeze)
    Object.freeze(value)
  }
  return value
}
freeze(fixtures); freeze(parameters); freeze(procedures)

function options(seed: number, received?: HarvestCommand[]): HarvestRunOptions {
  return { seed, startDay: 0, yearLengths: [365, 365, 365, 365, 365], harvestDays: [0, 0, 0, 0, 0],
    institution: parameters.institution, domain: parameters.domain, backingActor: parameters.backingActor,
    fixtures, procedures, providers: (fixture, random) => {
      const provider = createHarvestStubs(fixture, random, parameters)
      return { ...provider,
        collect: (commands, rows) => { received?.push(...commands); return provider.collect(commands, rows) },
        execute: command => { received?.push(command); return provider.execute(command) },
      }
    } }
}
const digest = (value: unknown) => createHash('sha256').update(JSON.stringify(value)).digest('hex')
type Trace = ReturnType<typeof runLegitimacyHarvest>
let trace: Trace, repeat: Trace, other: Trace
const received: HarvestCommand[] = []

describe('DESIGN section 3.1 seeded harvest run', () => {
  beforeAll(() => {
    trace = runLegitimacyHarvest(options(42, received))
    repeat = runLegitimacyHarvest(options(42))
    other = runLegitimacyHarvest(options(43))
    // Diagnostic evidence for HANDOFF; acceptance outcomes belong to the next unit.
    for (const [seed, run] of [[42, trace], [43, other]] as const) {
      for (const variant of ['A', 'B'] as const) {
        const before = run[variant][729], shock = run[variant][730]
        process.stdout.write(`Stub evidence: ${JSON.stringify({ seed, variant, R: [before.R, shock.R],
          backing: [before.backing.C, shock.backing.C],
          shockPaid: shock.payments.reduce((sum, row) => sum + (row.paid ?? 0), 0),
          paymentBreaches: shock.breaches.filter(b => b.act.action === 'omit:pay').length })}\n`)
      }
    }
  })

  it('same seed returns the same complete trace; another seed changes harvested inputs', () => {
    expect(digest(repeat)).toBe(digest(trace))
    expect(digest(other)).not.toBe(digest(trace))
    expect(other.A[0].input).not.toEqual(trace.A[0].input)
    // Both variants get the same external treatment and common random numbers.
    expect(trace.A.filter(d => d.harvest).map(d => d.input)).toEqual(trace.B.filter(d => d.harvest).map(d => d.input))
  })

  it.each(['A', 'B'] as const)('%s runs daily for five years with one marked input shock in year 3', variant => {
    const days = trace[variant]
    expect(days).toHaveLength(1825)
    expect(days.map(d => d.day)).toEqual(Array.from({ length: 1825 }, (_, i) => i))
    expect(days.filter(d => d.shock).map(d => [d.day, d.year])).toEqual([[730, 3]])
    expect(days.filter(d => d.harvest)).toHaveLength(5)
    expect(days.filter(d => !d.harvest).every(d => d.assessments.length === 0)).toBe(true)
    expect(days.filter(d => d.harvest).every(d => d.assessments.length === 60)).toBe(true)
  })

  it('routes every command through its owner provider and leaves input owner state untouched', () => {
    const commands = [...trace.A, ...trace.B].flatMap(d => d.commands)
    expect(received).toEqual(commands)
    expect(commands.some(c => c.owner === 'economy' && c.type === 'transfer')).toBe(true)
    expect(commands.some(c => c.owner === 'settlement' && c.type === 'pay')).toBe(true)
    expect(commands.every(c => c.owner === 'economy' || c.owner === 'settlement')).toBe(true)
    expect(parameters.households[first].grain).toBe(0)
    expect(parameters.households[first].belief).toBe(1)
    for (const day of [...trace.A, ...trace.B]) {
      const snapshot = day.owners as StubOwnerSnapshot
      expect(snapshot.grain.closing).toBeCloseTo(snapshot.grain.opening + snapshot.grain.harvested - snapshot.grain.consumed, 8)
      expect(snapshot.balances.every(b => b.amount >= 0)).toBe(true)
      expect(snapshot.coinsMoved).toBe(0)
    }
  })

  it('uses evaluator breaches and presentment stages without inventing a fine or seizure', () => {
    const shock = trace.A.find(d => d.shock)!
    const theft = shock.courts.find(c => c.stages[0].act.action === 'steal')!
    expect(theft.procedure).toBe('government/procedure.manorial-court-presentment-by-jurors-or-homage')
    expect(theft.stages.map(v => v.stage)).toEqual(['breach', 'detected', 'prosecuted'])
    expect(theft.stages[0].known_to).toEqual([])
    expect(theft.stages[1].known_to).toEqual([first])
    expect(shock.commands.find(c => c.owner === 'settlement')).toMatchObject({ type: 'pay', amount: null })
    expect(shock.breaches.some(b => b.act.action === 'omit:pay')).toBe(true)
    expect(shock.commands.some(c => 'kind' in c && c.kind === 'seizure')).toBe(false)
    expect((shock.owners as StubOwnerSnapshot).unresolved).toContain('settlement:pay: execution details not supplied')
  })

  it('recomputes recognition and backing from attributed provider beliefs each day', () => {
    for (const variant of ['A', 'B'] as const) {
      const beliefs = new Map(fixtures[variant].households.map(h => [h.id, parameters.households[h.id].belief!]))
      for (const day of trace[variant]) {
        for (const update of day.beliefUpdates) {
          expect(update.before).toBe(beliefs.get(update.person))
          expect(update.cause).toContain('attributed to court')
          beliefs.set(update.person, update.after!)
        }
        expect(day.R).toBeCloseTo([...beliefs.values()].reduce((a, b) => a + b, 0) / beliefs.size)
        expect(day.backing.C).toBe(beliefs.get(first))
      }
    }
  })

  it('keeps unknown beliefs and unobserved offences explicit instead of forcing outcomes', () => {
    const setup = options(42)
    setup.providers = (fixture, random) => createHarvestStubs(fixture, random, { ...parameters,
      choosePayment: () => 0,
      updateBelief: () => ({ belief: null, cause: 'Institution attribution unresolved' }),
      present: () => ({ witnesses: [], present: true }) })
    const unknown = runLegitimacyHarvest(setup)
    expect(unknown.A[0].R).toBeNull()
    expect(unknown.A[0].recognition.missingCount).toBe(60)
    expect(unknown.A[0].backing.flags).toHaveLength(1)
    expect(unknown.A[0].courts.every(c => c.stages.length === 1)).toBe(true)
    expect(unknown.A[0].commands).toEqual([])
  })

  it('validates the host calendar and requires unresolved modelling parameters', () => {
    expect(() => runLegitimacyHarvest({ ...options(42), harvestDays: [0, 0, 365, 0, 0] })).toThrow('calendar')
    expect(() => createHarvestStubs(fixtures.A, streams(42), { ...parameters, shockMultiplier: 1 })).toThrow('shock')
    expect(() => createHarvestStubs(fixtures.A, streams(42), { ...parameters, note: '' })).toThrow('note')
  })
})
